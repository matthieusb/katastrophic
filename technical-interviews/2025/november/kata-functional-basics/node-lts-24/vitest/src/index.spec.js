function getRandomNumberArray(count, min, max) {
    const data = [];
    for (let i = 0; i < count; ++i) {
        data.push(getRandomNumber(min, max))
    }
    return data;
}

function getRandomNumber(min, max) {
    return Math.floor(Math.random() * (max - min) + min);
}

